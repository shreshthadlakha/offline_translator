/**
 * The engine to use for a pair. Order of choice: a single pair small model,
 * then a verified group small model, then the full model. A quarantined
 * entry is kept but skipped, so those pairs fall to the full model. A pair
 * of two non English languages uses the full model; nothing pivots through
 * English.
 */
export function engineForPair(src: string, tgt: string, fastModelsEnabled: boolean): PairEngine {
  if (fastModelsEnabled) {
    const fast = ENGINE_TABLE[`${src}|${tgt}`];
    if (fast && !fast.disabled) return fast;
  }
  return NLLB_ENGINE;
}

/** What a pair costs to set up: which kind of engine, how many bytes, and
 * its measured quality tier (the label beside the size in the pickers). */
export type PairCost = {
  kind: "fast" | "group" | "large";
  expectedBytes: number;
  /** best: within the bar. good: approximate (borderline). limited:
   *  measurably weaker, still the best small option found. full: the full
   *  model serves this pair. */
  tier: QualityTier;
};

/**
 * The up front cost of a pair, for the quiet notes beside every language in
 * the picker and the language grid. English on either side can have a small
 * model; a pair of two non English languages always needs the full model.
 * The tier comes from the measured quality data (lib/quality.ts, regenerated
 * with the quality table after any route change), so a label is never shown
 * without data behind it.
 */
export function pairCost(src: string, tgt: string, fastModelsEnabled: boolean): PairCost {
  const engine = engineForPair(src, tgt, fastModelsEnabled);
  const tier = fastModelsEnabled ? directionQuality(src, tgt)?.tier ?? "full" : "full";
  if (engine.kind === "nllb") return { kind: "large", expectedBytes: engine.expectedBytes, tier: "full" };
  return { kind: engine.group ? "group" : "fast", expectedBytes: engine.expectedBytes, tier };
}

/** True when this pair carries a "use the full model" override in settings. */
export function hasFullModelOverride(list: string[] | undefined, src: string, tgt: string): boolean {
  if (!list || list.length === 0) return false;
  return list.includes(`${src}|${tgt}`);
}

/** True when this pair's engine would be the large full model. */
export function isLargePair(src: string, tgt: string, fastModelsEnabled: boolean): boolean {
  return engineForPair(src, tgt, fastModelsEnabled).kind === "nllb";
}

/**
 * True when this pair needs the large full model and the optional
 * "Hide languages that need the large model" switch hides it. The switch is
 * off by default: the large-model languages are offered normally, with their
 * plain tag. This is exactly the default-list case: the pair has no fast
 * route at all, fast models are on, no per-pair override asked for the full
 * model, and hiding is on. Explicit asks ("Use faster models" off globally,
 * or the per-pair "Use the full model for this language" button) are choices,
 * not missing small models, and stay offered with the honest warning.
 */
export function largePairHidden(
  src: string,
  tgt: string,
  fastModelsEnabled: boolean,
  overrides: string[] | undefined,
  hideLargeLanguages: boolean,
): boolean {
  if (!hideLargeLanguages) return false;
  if (!fastModelsEnabled) return false;
  if (hasFullModelOverride(overrides, src, tgt)) return false;
  return isLargePair(src, tgt, true);
}

/**
 * The pair to open the page on. The last used pair is kept as it was; when it
 * needs the large model, the page opens on the last pair that used a small
 * model instead, or on English to French when no such pair exists under the
 * current settings. The large model is never started by opening the page, so
 * nothing that needs it is restored either. Codes are validated against the
 * registry.
 */
export function restoredPair(settings: {
  lastSrc: string;
  lastTgt: string;
  lastSmallSrc: string;
  lastSmallTgt: string;
  useFastModels: boolean;
  fullModelFor: string[];
}): { src: string; tgt: string; changed: boolean } {
  const fast = (src: string, tgt: string) =>
    settings.useFastModels && !settings.fullModelFor.includes(`${src}|${tgt}`);
  const valid = (code: string, fallback: string) =>
    languageByCode(code)?.code ?? fallback;
  const last = {
    src: valid(settings.lastSrc, "eng_Latn"),
    tgt: valid(settings.lastTgt, "fra_Latn"),
  };
  if (!isLargePair(last.src, last.tgt, fast(last.src, last.tgt))) {
    return { ...last, changed: false };
  }
  const small = {
    src: valid(settings.lastSmallSrc, "eng_Latn"),
    tgt: valid(settings.lastSmallTgt, "fra_Latn"),
  };
  if (!isLargePair(small.src, small.tgt, fast(small.src, small.tgt))) {
    return { ...small, changed: true };
  }
  return { src: "eng_Latn", tgt: "fra_Latn", changed: true };
}

/**
 * The pair that would result from picking a language on one side, including
 * the swap that happens when it is already set on the other side.
 */
export function resultingPair(side: "source" | "target", code: string, src: string, tgt: string): { src: string; tgt: string } {
  if (side === "source") {
    return code === tgt ? { src: code, tgt: src } : { src: code, tgt };
  }
  return code === src ? { src: tgt, tgt: code } : { src, tgt: code };
}

/** Every engine the app can end up with, for listings and licenses.
 * Quarantined engines (no live route left) are not listed: they are never
 * downloaded, so they never appear in Settings or the notices. */
export function allEngines(): EngineDescriptor[] {
  const seen = new Map<string, EngineDescriptor>();
  for (const pair of Object.values(ENGINE_TABLE)) {
    if (pair.disabled) continue;
    if (!seen.has(pair.id)) seen.set(pair.id, pair);
  }
  return [NLLB_ENGINE, ...seen.values()];
}

export function engineById(id: string): EngineDescriptor | undefined {
  return allEngines().find((engine) => engine.id === id);
}
