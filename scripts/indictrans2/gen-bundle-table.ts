/**
 * Generates src/lib/indictrans2/bundles.ts from the pinned manifest
 * (scripts/indictrans2/cache/manifest.json). The SHA-256 values become part
 * of the app source: the worker verifies every file against them before
 * using or caching it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const manifest = JSON.parse(
  readFileSync(path.join(import.meta.dir, "cache", "manifest.json"), "utf8"),
);

const repos: Record<string, { repo: string; commit: string }> = {
  "en-indic": {
    repo: "hari31416/indictrans2-en-indic-dist-200M-ONNX-int8",
    commit: "1eaa43a3fb76f382f1b22c76e56f6ab4926ad68b",
  },
  "indic-en": {
    repo: "hari31416/indictrans2-indic-en-dist-200M-ONNX-int8",
    commit: "a7ecdc0ba73148c6e1d051ca372332471d8aff4f",
  },
};

function emit(key: string): string {
  const { repo, commit } = repos[key]!;
  const files = manifest[key] as Record<string, { bytes: number; sha256: string }>;
  const total = Object.values(files).reduce((s, f) => s + f.bytes, 0);
  const entries = Object.entries(files)
    .map(([name, f]) => `    { name: ${JSON.stringify(name)}, bytes: ${f.bytes}, sha256: ${JSON.stringify(f.sha256)} },`)
    .join("\n");
  return `  "${key}": {
    repo: ${JSON.stringify(repo)},
    commit: ${JSON.stringify(commit)},
    totalBytes: ${total},
    files: [
${entries}
    ],
  },`;
}

const source = `/**
 * The pinned IndicTrans2 bundles. Files load straight from the Hugging Face
 * Hub at exact commit hashes; every file's SHA-256 is verified before the
 * bytes are used or cached. GENERATED by scripts/indictrans2/gen-bundle-table.ts
 * from cache/manifest.json (p5a); edit that pipeline, not this file, if a
 * bundle ever moves.
 *
 * Bundles (MIT license, AI4Bharat IndicTrans2 distilled 200M, ONNX int8
 * conversions by hari31416):
 *   en-indic   English -> 22 scheduled Indic languages (309 MB)
 *   indic-en   22 scheduled Indic languages -> English (262 MB)
 */

export type IndicTrans2BundleKey = "en-indic" | "indic-en";

export type PinnedFile = {
  name: string;
  bytes: number;
  sha256: string;
};

export type PinnedBundle = {
  repo: string;
  commit: string;
  totalBytes: number;
  files: PinnedFile[];
};

export const INDICTRANS2_BUNDLES: Record<IndicTrans2BundleKey, PinnedBundle> = {
${emit("en-indic")}
${emit("indic-en")}
};

/** The URL a bundle file loads from, pinned to the exact commit. */
export function bundleFileUrl(bundle: IndicTrans2BundleKey, file: string): string {
  const b = INDICTRANS2_BUNDLES[bundle];
  return \`https://huggingface.co/\${b.repo}/resolve/\${b.commit}/\${file}\`;
}

/** The languages each bundle serves on its source side (FLORES codes,
 * English excluded). From the IndicTrans2 model cards. */
export const INDICTRANS2_LANGUAGES: string[] = [
  "asm_Beng", "ben_Beng", "brx_Deva", "doi_Deva", "gom_Deva", "gon_Deva",
  "guj_Gujr", "hin_Deva", "hne_Deva", "kan_Knda", "kas_Arab", "kas_Deva",
  "kha_Latn", "lus_Latn", "mag_Deva", "mai_Deva", "mal_Mlym", "mar_Deva",
  "mni_Beng", "mni_Mtei", "npi_Deva", "ory_Orya", "pan_Guru", "san_Deva",
  "sat_Olck", "snd_Arab", "snd_Deva", "tam_Taml", "tel_Telu", "urd_Arab",
  "unr_Deva", "awa_Deva", "bho_Deva",
];

export function bundleForDirection(src: string, tgt: string): IndicTrans2BundleKey | null {
  if (src === "eng_Latn" && INDICTRANS2_LANGUAGES.includes(tgt)) return "en-indic";
  if (tgt === "eng_Latn" && INDICTRANS2_LANGUAGES.includes(src)) return "indic-en";
  return null;
}
`;

writeFileSync(path.join(import.meta.dir, "..", "..", "src", "lib", "indictrans2", "bundles.ts"), source);
console.log("wrote src/lib/indictrans2/bundles.ts");
